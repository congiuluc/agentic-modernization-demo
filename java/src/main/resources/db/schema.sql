CREATE TABLE IF NOT EXISTS blog_admins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL
);
CREATE TABLE IF NOT EXISTS categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  slug VARCHAR(150) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS blog_posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  slug VARCHAR(150) NOT NULL UNIQUE,
  body CLOB NOT NULL,
  published BOOLEAN NOT NULL,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  published_at TIMESTAMP NULL,
  category_id BIGINT NOT NULL REFERENCES categories(id)
);
CREATE TABLE IF NOT EXISTS blog_comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  author VARCHAR(100) NOT NULL,
  body VARCHAR(2000) NOT NULL,
  approved BOOLEAN NOT NULL,
  created_at TIMESTAMP NOT NULL,
  post_id BIGINT NOT NULL REFERENCES blog_posts(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_posts_publication ON blog_posts(published, published_at, id);
CREATE INDEX IF NOT EXISTS ix_posts_category ON blog_posts(category_id);
CREATE INDEX IF NOT EXISTS ix_comments_post ON blog_comments(post_id, approved);
CREATE TABLE IF NOT EXISTS seed_state (id VARCHAR(32) PRIMARY KEY);
